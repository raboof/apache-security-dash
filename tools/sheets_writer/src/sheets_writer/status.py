    # pipeline state as of that date (state = the latest milestone reached). ISO
    # date strings compare lexically, so plain <= works.
    def _state_asof(e: dict, d: str) -> str | None:
        for date_key, st in (
            ("forwarded_date", "Delivered"),
            ("received_date", "Triaging"),
            ("submitted_date", "Submitted"),
            ("model_verified_date", "Ready"),
            ("request_date", "Pre-flight"),
        ):
            if e[date_key] and e[date_key] <= d:
                return st
        return None

    timeline_dates = sorted(
        {
            d
            for e in entries
            for d in (
                e["request_date"],
                e["model_verified_date"],
                e["submitted_date"],
                e["received_date"],
                e["forwarded_date"],
            )
            if d
        }
    )
    timeseries = []
    for d in timeline_dates:
        counts = dict.fromkeys(PIPELINE_STATES, 0)
        for e in entries:
            st = _state_asof(e, d)
            if st:
                counts[st] += 1
        timeseries.append((d, [counts[s] for s in PIPELINE_STATES]))

    # Repo-granularity funnel over the same milestone dates: each PMC's repos
    # progress through the pipeline (submitted repos reach Submitted+, the rest
    # cap at Ready). Drives the second stacked-area chart on the Timeline tab.
    repo_timeseries = repo_funnel_timeseries(entries, timeline_dates, PIPELINE_STATES)

