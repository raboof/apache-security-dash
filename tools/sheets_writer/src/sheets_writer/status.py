def _parse_addrs(cell: str) -> list[str]:
    """Split an address cell on newlines / commas into a deduped, ordered list."""
    out: list[str] = []
    for part in (cell or "").replace(",", "\n").split("\n"):
        a = part.strip()
        if a and a not in out:
            out.append(a)
    return out


_ADDR_RE = re.compile(r"[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}")


def _normalize_addr(s: str) -> str:
    """Extract the bare email address from a possibly-annotated cell entry.

    Expedite/subscription cells carry status annotations after the address,
    e.g. ``rusackas@apache.org (registered)`` or
    ``villebro@apache.org (nominated; registration unconfirmed)``. The person
    registry stores — and dedups + resolves names on — the bare address only.
    Returns the first email found, else the stripped input.
    """
    m = _ADDR_RE.search(s or "")
    return m.group(0) if m else (s or "").strip()


def compute_subscription_syncs(
    grid: list[list[str]], col_idx: dict
) -> list[tuple[int, list[str], list[str]]]:
    """Pure: decide which PMC rows need expedite addresses appended to their
    ``Claude OSS Subscriptions Submitted`` cell.

    A PMC's expedite request counts as *submitted* once ``Date scan requested``
    is set (the expedite list rides the headline scan-submission form). The
    merge is an append-only union — addresses already in the Subscriptions cell
    are preserved, never removed. Returns ``(sheet_row, merged, new)`` per row
    that changes (``sheet_row`` is 1-based; the header occupies row 1).
    """
    exp_i = col_idx.get("Expedite Claude OSS Requests", -1)
    sub_i = col_idx.get("Claude OSS Subscriptions Submitted", -1)
    dsr_i = col_idx.get("Date scan requested", -1)
    if exp_i < 0 or sub_i < 0:
        return []  # required columns absent — nothing to sync

    def _cell(row: list[str], i: int) -> str:
        return row[i].strip() if 0 <= i < len(row) else ""

    out: list[tuple[int, list[str], list[str]]] = []
    for r, row in enumerate(grid[1:], start=2):  # sheet row number (header is row 1)
        if dsr_i >= 0 and not _cell(row, dsr_i):
            continue  # not yet submitted — expedite not relayed to the vendor
        expedite = _parse_addrs(_cell(row, exp_i))
        if not expedite:
            continue
        current = _parse_addrs(_cell(row, sub_i))
        new = [a for a in expedite if a not in current]
        if not new:
            continue
        out.append((r, current + new, new))
    return out


# Schema of the persistent 'OSS Subscriptions' registry tab. Name and the
# "Submitted manually" column are maintained by hand and preserved across
# refreshes; PMC + Date are auto-filled when a person is first appended. Email
# is the dedup key.
SUBSCRIPTION_REGISTRY_HEADER = ["Name", "Email", "PMC", "Date", "Submitted manually"]


def subscription_email_rows(grid: list[list[str]], col_idx: dict) -> list[tuple[str, str, str]]:
    """Pure: ``(email, pmc_slug, date)`` for every OSS-subscription address
    across **all** PMCs that carry an expedite/subscription address, deduped by
    email (first PMC wins).

    The address set per PMC is the union of ``Claude OSS Subscriptions
    Submitted`` and ``Expedite Claude OSS Requests``; ``date`` is the PMC's
    ``Request date`` (so an auto-appended person carries the same date shape as
    the hand-seeded rows).

    The registry tracks **everyone who registered** for the OSS expedite, not
    only PMCs whose scan has already been submitted: a person registers at
    claude-for-oss independently of when their PMC's scan is relayed, so they
    belong in the registry the moment their address lands in the Expedite cell.
    (The ``Claude OSS Subscriptions Submitted`` *cell* on the PMCs sheet stays
    submission-gated — see ``compute_subscription_syncs``.)
    """
    slug_i = col_idx.get("PMC Slug", -1)
    exp_i = col_idx.get("Expedite Claude OSS Requests", -1)
    sub_i = col_idx.get("Claude OSS Subscriptions Submitted", -1)
    req_i = col_idx.get("Request date", -1)
    if sub_i < 0 and exp_i < 0:
        return []

    def _cell(row: list[str], i: int) -> str:
        return row[i].strip() if 0 <= i < len(row) else ""

    seen: set[str] = set()
    out: list[tuple[str, str, str]] = []
    for row in grid[1:]:
        current = [_normalize_addr(a) for a in _parse_addrs(_cell(row, sub_i))]
        expedited = [_normalize_addr(a) for a in _parse_addrs(_cell(row, exp_i))]
        emails = current + [a for a in expedited if a not in current]
        slug = _cell(row, slug_i)
        date = _cell(row, req_i)
        for e in emails:
            if not e or e in seen:
                continue
            seen.add(e)
            out.append((e, slug, date))
    return out


def parse_subscription_registry(
    os_grid: list[list[str]],
) -> tuple[list[list[str]], set[str]]:
    """Pure: parse the existing 'OSS Subscriptions' tab into its data rows +
    the set of emails already present.

    Locates the ``SUBSCRIPTION_REGISTRY_HEADER`` row (the tab has title/summary
    rows above it); data rows are the subsequent rows with a non-empty Email.
    Each returned row is normalised to the 5 registry columns. Rows that don't
    match the header (e.g. an older tab layout) yield an empty registry, so the
    refresh re-seeds from scratch.
    """
    if not os_grid:
        return [], set()
    width = len(SUBSCRIPTION_REGISTRY_HEADER)
    header_at = -1
    for i, row in enumerate(os_grid):
        if [c.strip() for c in row[:width]] == SUBSCRIPTION_REGISTRY_HEADER:
            header_at = i
            break
    if header_at < 0:
        return [], set()
    rows: list[list[str]] = []
    emails: set[str] = set()
    for row in os_grid[header_at + 1 :]:
        email = _normalize_addr(row[1]) if len(row) > 1 else ""
        if not email:
            continue
        norm = [(row[j].strip() if j < len(row) else "") for j in range(width)]
        norm[1] = email  # store the bare address — self-heals annotated rows
        rows.append(norm)
        emails.add(email)
    return rows, emails


LDAP_PEOPLE_URL = "https://whimsy.apache.org/public/public_ldap_people.json"


def resolve_apache_names(emails: list[str]) -> dict[str, str]:
    """Map ``<id>@apache.org`` → committer full name via the Whimsy public LDAP
    people directory (``{"people": {"<id>": {"name": ...}}}``); the local-part of
    an ``@apache.org`` address *is* the Apache id.

    Best-effort and network-bound: fetched once with stdlib urllib (no
    summarising layer), and any failure (offline, timeout) returns ``{}`` so the
    status refresh still succeeds — unresolved names simply stay blank. Only
    ``@apache.org`` addresses are looked up; others are ignored.
    """
    ids: dict[str, str] = {}
    for e in emails:
        addr = _normalize_addr(e)
        if addr.endswith("@apache.org"):
            ids[addr.split("@", 1)[0]] = addr
    if not ids:
        return {}
    import json
    import urllib.request

    try:
        with urllib.request.urlopen(LDAP_PEOPLE_URL, timeout=30) as resp:  # noqa: S310
            people = json.load(resp).get("people", {})
    except Exception:  # noqa: BLE001 — name resolution is best-effort
        return {}
    out: dict[str, str] = {}
    for apache_id, addr in ids.items():
        name = (people.get(apache_id) or {}).get("name", "").strip()
        if name:
            out[addr] = name
    return out


def fill_registry_names(rows: list[list[str]], resolver=resolve_apache_names) -> int:
    """Fill a blank Name (column 0) on each registry row from the Apache
    committer directory, keyed by the row's ``@apache.org`` email (column 1).

    Auto-fills people the subscription sync appended with no name *and*
    backfills historical blank-name rows; a non-blank (hand-entered) Name is
    always preserved — manual edits win. ``resolver`` is injectable for tests.
    Returns the number of names filled. Mutates ``rows`` in place.
    """
    pending = [
        _normalize_addr(r[1]) for r in rows if len(r) > 1 and not r[0].strip() and r[1].strip()
    ]
    if not pending:
        return 0
    name_map = resolver(pending)
    filled = 0
    for r in rows:
        if len(r) > 1 and not r[0].strip():
            name = name_map.get(_normalize_addr(r[1]), "")
            if name:
                r[0] = name
                filled += 1
    return filled


# Schema of the 'Scan Queue' tab. "When scanned" and "Commit hash" are
