MANUAL_FILL = {"red": 1.0, "green": 0.97, "blue": 0.80}


def parse_criticality(raw: str) -> float | None:
    """Pure: parse an OSSF criticality cell ("48.3%", "0.483", "") into a float
    in [0, 100], or None when blank/unparseable (those sort last).

    A bare value <= 1 is treated as a 0..1 fraction and scaled to a percentage;
    anything larger is taken as an already-percentage number.
    """
    s = (raw or "").strip().rstrip("%").strip()
    if not s:
        return None
    try:
        v = float(s)
    except ValueError:
        return None
    return v * 100 if v <= 1 else v


def scan_queue_auto_rows(
    grid: list[list[str]], col_idx: dict, repos_grid: list[list[str]]
) -> list[dict]:
    """Pure: one record per *submitted* repo, sorted by OSSF criticality
    (descending; blank last), then repo URL.

    A repo is "submitted" iff it appears in some PMC row's ``Repositories
    submitted`` cell. Each record carries the auto-derived fields the Scan Queue
    tab renders: ``repo`` (GitHub URL — the stable key the manual columns are
    keyed by), ``pmc``, ``crit`` (display string from the Repositories sheet),
    ``crit_val`` (float|None sort key), ``when_ready`` (``Date scan requested``),
    and ``when_report_sent`` (``Forwarded scan to PMC``).
    """
    name_i = col_idx.get("PMC Name", -1)
    slug_i = col_idx.get("PMC Slug", -1)
    sub_i = col_idx.get("Repositories submitted", -1)
    dsr_i = col_idx.get("Date scan requested", -1)
    fwd_i = col_idx.get("Forwarded scan to PMC", -1)
    if sub_i < 0:
        return []

    # Criticality display string per repo URL, from the Repositories sheet.
    crit_by_url: dict[str, str] = {}
    if repos_grid:
        rhdr = {h: i for i, h in enumerate(repos_grid[0])}
        url_j = rhdr.get("Repository URL", -1)
        crit_j = rhdr.get("Criticality Score (%)", -1)
        if url_j >= 0:
            for rr in repos_grid[1:]:
                url = rr[url_j].strip() if url_j < len(rr) else ""
                if url:
                    crit_by_url[url] = rr[crit_j].strip() if 0 <= crit_j < len(rr) else ""

    def _cell(row: list[str], i: int) -> str:
        return row[i].strip() if 0 <= i < len(row) else ""

    out: list[dict] = []
    for row in grid[1:]:
        submitted = [
            ln.strip()
            for ln in _cell(row, sub_i).splitlines()
            if ln.strip() and not ln.strip().startswith("#")
        ]
        if not submitted:
            continue
        pmc = _cell(row, name_i) or _cell(row, slug_i)
        when_ready = _cell(row, dsr_i)
        when_report = _cell(row, fwd_i)
        for url in submitted:
            crit_str = crit_by_url.get(url, "")
            out.append(
                {
                    "repo": url,
                    "pmc": pmc,
                    "crit": crit_str,
                    "crit_val": parse_criticality(crit_str),
                    "when_ready": when_ready,
                    "when_report_sent": when_report,
                }
            )
    out.sort(key=lambda e: (-(e["crit_val"] if e["crit_val"] is not None else -1.0), e["repo"]))
    return out


def parse_scan_queue(sq_grid: list[list[str]]) -> dict[str, tuple[str, str]]:
    """Pure: map ``repo URL -> (when_scanned, commit_hash)`` from the existing
    'Scan Queue' tab, so hand-entered values survive a rebuild.

    Locates the ``SCAN_QUEUE_HEADER`` row (the tab has title/summary rows above
    it); rows below it with a non-empty Repo contribute their two manual
    columns. Keying by Repo (not row position) is what lets the manual data
    follow its repo when the table is re-sorted or new rows are inserted. A tab
    that doesn't match the header yields ``{}`` (the rebuild re-seeds with blank
    manual columns).
    """
    if not sq_grid:
        return {}
    width = len(SCAN_QUEUE_HEADER)
    header_at = -1
    for i, row in enumerate(sq_grid):
        if [c.strip() for c in row[:width]] == SCAN_QUEUE_HEADER:
            header_at = i
            break
    if header_at < 0:
        return {}
    ws_j, ch_j = SCAN_QUEUE_MANUAL_COLS
    out: dict[str, tuple[str, str]] = {}
    for row in sq_grid[header_at + 1 :]:
        repo = row[0].strip() if row else ""
        if not repo:
            continue
        ws = row[ws_j].strip() if ws_j < len(row) else ""
        ch = row[ch_j].strip() if ch_j < len(row) else ""
        out[repo] = (ws, ch)
    return out


def repo_state_counts_asof(e: dict, d: str, states: list[str]) -> dict[str, int]:
    """Pure: repo counts for one PMC entry in each pipeline state as of date ``d``.

    The repo analogue of ``_state_asof`` (which places a whole PMC in one state).
    A PMC's *submitted* repos (``repos_submitted_count``) progress through
    Submitted -> Triaging -> Delivered as the PMC's milestone dates pass.

    The requested-but-not-submitted remainder is the subtle part. A repo only
    counts as **Ready** when it is genuinely *waiting only for the operator's
    go-ahead* — i.e. its PMC is wholesale ready: model verified AND nothing
    submitted yet. Once a PMC has *begun* submitting, the repos it left out were
    deliberately held back (per-repo discoverability not yet in place, a
    branch-scoped repo the form can't target, etc.) — those are not ready, so
    they stay in **Pre-flight** rather than counting as Ready. (This is why e.g.
    Logging's 17 deferred repos, which still lack AGENTS.md, must not show as
    Ready.)

    Before a given milestone's date the repos sit in the latest state actually
    reached, so each PMC's per-date total stays equal to its requested-repo
    count — a clean stacked funnel. ISO date strings compare lexically, so plain
    ``<=`` works.
    """
    counts = dict.fromkeys(states, 0)
    n_sub = e.get("repos_submitted_count", 0)
    n_non = max(0, e.get("repos_requested_count", 0) - n_sub)

    def _first(seq: tuple[tuple[str, str], ...]) -> str | None:
        for date_key, st in seq:
            v = e.get(date_key)
            if v and v <= d:
                return st
        return None

    # Submitted repos progress through the full pipeline.
    sub_state = _first(
        (
            ("forwarded_date", "Delivered"),
            ("received_date", "Triaging"),
            ("submitted_date", "Submitted"),
            ("model_verified_date", "Ready"),
            ("request_date", "Pre-flight"),
        )
    )
    if sub_state and n_sub:
        counts[sub_state] += n_sub

    # Non-submitted requested repos.
    if n_non:
        if e.get("submitted_date"):
            # PMC already started submitting; the remainder was held back (not
            # yet submittable), so it is NOT ready — it sits in Pre-flight from
            # the request date onward, never advancing to Ready.
            req = e.get("request_date")
            non_state = "Pre-flight" if (req and req <= d) else None
        else:
            # Nothing submitted yet: a verified model means these repos are
            # genuinely waiting only for the operator go-ahead -> Ready.
            non_state = _first(
                (
                    ("model_verified_date", "Ready"),
                    ("request_date", "Pre-flight"),
                )
            )
        if non_state:
            counts[non_state] += n_non
    return counts


def repo_funnel_timeseries(
    entries: list[dict], dates: list[str], states: list[str]
) -> list[tuple[str, list[int]]]:
    """Pure: per-date repo counts summed across all PMC entries — one ``(date,
    counts)`` pair per date in ``dates``, the inner list in ``states`` order.
    The repo-granularity counterpart of the PMC funnel-over-time series.
    """
    out: list[tuple[str, list[int]]] = []
    for d in dates:
        agg = dict.fromkeys(states, 0)
        for e in entries:
            c = repo_state_counts_asof(e, d, states)
            for s in states:
                agg[s] += c[s]
        out.append((d, [agg[s] for s in states]))
    return out


def sync_oss_subscriptions(
    service, spreadsheet_id: str, grid: list[list[str]], col_idx: dict
) -> int:
    """Append each *submitted* PMC's expedite addresses into its
    ``Claude OSS Subscriptions Submitted`` cell (append-only union; never
    removes). Runs on every ``build-status-tab`` refresh so the column stays in
    sync with the expedite asks. Returns the number of PMC rows updated.
    """
    sub_i = col_idx.get("Claude OSS Subscriptions Submitted", -1)
    syncs = compute_subscription_syncs(grid, col_idx)
    if not syncs:
        return 0
    data = [
        {"range": f"PMCs!{col_letter(sub_i)}{r}", "values": [["\n".join(merged)]]}
        for r, merged, _new in syncs
    ]
    service.spreadsheets().values().batchUpdate(
        spreadsheetId=spreadsheet_id,
        body={"valueInputOption": "USER_ENTERED", "data": data},
    ).execute()
    print(f"Synced OSS subscriptions ({len(data)} PMC row(s)):")
    for r, _merged, new in syncs:
        print(f"  PMCs row {r} · Claude OSS Subscriptions Submitted += {new}")
    return len(data)


def cmd_build_status_tab(args: argparse.Namespace) -> None:
    service = get_service()
    today = datetime.date.today().isoformat()

    # 1. Read source data.
    grid = fetch_sheet_grid(service, args.spreadsheet_id, "PMCs")
    if not grid or len(grid) < 2:
        sys.exit("PMCs sheet has no data rows.")
    header = grid[0]
    col_idx = {h: i for i, h in enumerate(header)}

    entries = []
    for row in grid[1:]:
        scan_requested_idx = col_idx.get("Scan Requested", -1)
